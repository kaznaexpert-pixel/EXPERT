    <h2 id="faq">Частые вопросы</h2>
    <div class="faq">
      <details open><summary>Что происходит с авансом на счёте при расторжении?</summary><p>Неотработанная часть аванса возвращается источнику — заказчику или в доход бюджета. Отработанная часть, подтверждённая приёмкой, остаётся исполнителю. Сумму к возврату определяют по выписке после закрытия всех расчётов.</p></details>
      <details><summary>Можно ли закрыть счёт сразу после расторжения?</summary><p>Нет. Сначала нужно завершить расчёты, вернуть неотработанный аванс и остаток целевых средств и дождаться нулевого остатка по выписке. Только после этого ТОФК закроет счёт по заявлению.</p></details>
      <details><summary>Грозит ли РНП при расторжении?</summary><p>При расторжении по соглашению сторон — нет. Реестр недобросовестных поставщиков грозит при одностороннем отказе заказчика из-за нарушений исполнителя или по решению суда.</p></details>
      <details><summary>Кто определяет сумму возврата?</summary><p>Стороны фиксируют отработанный объём в актах приёмки, а сумму к возврату считают по исходящему остатку лицевого счёта. При споре размер определяется претензионно или в суде.</p></details>
      <details><summary>Что делать с авансами соисполнителей?</summary><p>Неотработанные авансы кооперации возвращаются на головной целевой счёт до возврата остатка заказчику. Иначе остаток не обнулится и счёт не закрыть.</p></details>
      <details><summary>Можно ли удержать неустойку из суммы возврата?</summary><p>Заказчик вправе удержать пени и штрафы из причитающихся исполнителю сумм или предъявить их отдельно. Возврат неотработанного аванса при этом остаётся обязательным.</p></details>
      <details><summary>Что будет, если аванс потрачен не на цель контракта?</summary><p>Это нецелевое использование: добавляется ответственность по ст. 15.14 КоАП РФ, а казначейство фиксирует нарушение режима целевых средств. Возврат при этом всё равно обязателен.</p></details>
      <details><summary>Чем расторжение отличается от завершения при исполнении?</summary><p>Финал одинаков — возврат остатка и закрытие счёта, — но при расторжении доля возврата обычно выше (неотработанный аванс) и добавляются последствия по 44-ФЗ: РНП, неустойка, споры о приёмке.</p></details>
      <details><summary>Что с обеспечением контракта при расторжении?</summary><p>Обеспечение исполнения возвращается при надлежащем расторжении; при нарушениях из него удерживают неустойку. Неиспользованное казначейское обеспечение обязательств отзывается.</p></details>
      <details><summary>Действует ли подпись и запись в реестре после закрытия счёта?</summary><p>Да. Квалифицированный сертификат действует до окончания срока, запись в сводном реестре сохраняется. Под новый контракт открывается новый лицевой счёт без повторного включения в реестр.</p></details>
