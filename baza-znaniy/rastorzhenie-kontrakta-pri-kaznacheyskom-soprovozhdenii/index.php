    <p>Общая часть процедуры — возврат и закрытие счёта — подробно разобрана в материале о <a href="/baza-znaniy/zavershenie-kaznacheyskogo-soprovozhdeniya/">завершении казначейского сопровождения</a>. При расторжении к ней добавляется этап определения отработанной части аванса и работа с последствиями по 44-ФЗ.</p>

    <h2 id="sudebnoe">Судебное расторжение и заморозка счёта</h2>
    <p>Когда стороны не договорились, а оснований для одностороннего отказа недостаточно, расторжение уходит в суд. Это самый долгий сценарий, и для казначейского контура он означает простой: пока спор не разрешён, остаток на лицевом счёте фактически заморожен. Распорядиться им нельзя, вернуть — тоже, потому что неизвестна итоговая сумма к возврату.</p>
    <p>На время судебного разбирательства лицевой счёт остаётся открытым, а целевые средства — под режимом. Это создаёт встречный интерес: и заказчику, и исполнителю выгоднее закрыть спор по существу быстрее, чтобы разблокировать деньги. Поэтому даже при принципиальном конфликте часть вопросов — например, бесспорную сумму возврата неотработанного аванса — стороны нередко урегулируют отдельным соглашением, не дожидаясь решения по основному спору. После вступления решения суда в силу возврат и закрытие счёта проходят по общей процедуре: сверка остатка по выписке, распоряжение на возврат, обнуление, заявление на закрытие.</p>

    <h2 id="sroki">Сроки возврата и просрочка</h2>
    <p>Срок возврата неотработанного аванса и остатка целевых средств задаётся не общим правилом, а условиями контракта (соглашения о расторжении) и правилами текущего года. Как правило, возврат привязан к моменту расторжения: средства возвращаются в установленный контрактом срок после подписания соглашения или вступления в силу решения об отказе.</p>
    <p>Отдельный ориентир — конец финансового года: для ряда целевых средств действуют годовые правила, по которым неиспользованные остатки возвращаются в установленные сроки декабря независимо от того, расторгнут контракт или нет. Просрочка возврата невыгодна самому исполнителю: деньги всё равно придётся вернуть, но к этому добавятся претензии заказчика, а незакрытый счёт с остатком будет числиться за организацией. Поэтому возврат планируют заранее, а не в последний день, — особенно если расторжение приходится на конец года.</p>

