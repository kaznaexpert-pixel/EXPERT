    <h2 id="schet-ostatok">Что происходит со счётом и остатком</h2>
    <p>При расторжении лицевой счёт 71 не исчезает автоматически. Он продолжает существовать вместе с остатком до тех пор, пока стороны не проведут взаиморасчёты и не вернут неиспользованные деньги. На счёте может оказаться три типа сумм.</p>
    <table>
      <caption>Что лежит на счёте к моменту расторжения</caption>
      <tr><th>Сумма</th><th>Природа</th><th>Судьба при расторжении</th></tr>
      <tr><td>Неотработанный аванс</td><td>Целевые средства, под которые ещё не выполнены работы</td><td>Возвращается источнику (заказчику / в бюджет)</td></tr>
      <tr><td>Остаток по оплаченным, но не закрытым обязательствам</td><td>Зарезервированные под распоряжения средства</td><td>Распоряжение проводится или отзывается, затем сверяется остаток</td></tr>
      <tr><td>Подтверждённая прибыль и экономия</td><td>Заработок по фактически исполненной части</td><td>Выводится на расчётный счёт по правилам года, возврату не подлежит</td></tr>
    </table>
    <p>Размер итогового остатка к возврату определяют по исходящему остатку последней выписки после всех проводок. Здесь та же логика, что и при штатном <a href="/baza-znaniy/zavershenie-kaznacheyskogo-soprovozhdeniya/">завершении сопровождения</a>: пока остаток не обнулён, счёт не закрыть. Разница лишь в том, что при расторжении доля возврата обычно выше — ведь часть работ не выполнена и аванс отработан не полностью.</p>
    <div class="note"><b>Важно.</b> Возврату подлежит именно неотработанный аванс и неизрасходованный целевой остаток, а не вся сумма со счёта. Прибыль и оплата за принятую заказчиком часть работ остаются исполнителю. Разделять эти потоки нужно до того, как формировать распоряжение на возврат.</div>

    <h2 id="vozvrat">Возврат аванса и остатка: пошагово</h2>
    <p>Возврат при расторжении — управляемая процедура. Чтобы она не превратилась в зависшие на счёте деньги и спор с заказчиком, её проходят по порядку.<a class="fn" href="#ref-2" aria-label="Источник 2">[2]</a></p>
    <h3>Шаг 1. Зафиксируйте объём исполненного</h3>
    <p>Подпишите с заказчиком документы о приёмке фактически выполненной части (акты, накладные). От этого зависит, какая доля аванса считается отработанной, а какая — подлежит возврату.</p>
    <h3>Шаг 2. Закройте расчёты с соисполнителями</h3>
    <p>Проведите окончательные платежи поставщикам по принятым позициям и верните на счёт неотработанные авансы соисполнителей. Незакрытый аванс соисполнителя — частая причина, по которой остаток не обнуляется.</p>
    <h3>Шаг 3. Определите сумму к возврату по выписке</h3>
    <p>Сформируйте выписку на дату расторжения и зафиксируйте исходящий остаток целевых средств. Это и есть сумма, которую нужно вернуть источнику.</p>
    <h3>Шаг 4. Уточните реквизиты и сформируйте распоряжение</h3>
    <p>Реквизиты возврата возьмите из контракта (соглашения о расторжении) и сверьте с заказчиком. Возврат проводится <a href="/baza-znaniy/rasporyazhenie-o-sovershenii-kaznacheyskogo-platezha/">распоряжением о казначейском платеже</a> с целевого счёта, с корректным назначением «возврат неотработанного аванса / остатка целевых средств».</p>
    <h3>Шаг 5. Обнулите остаток и закройте счёт</h3>
    <p>После проведения возврата проверьте по следующей выписке, что исходящий остаток стал нулевым, и подайте заявление на закрытие лицевого счёта в «Электронном бюджете». ТОФК закрывает счёт по приказу № 21н при нулевом остатке и отсутствии неисполненных распоряжений.</p>

    <h2 id="odnostoronnee">Одностороннее расторжение заказчиком</h2>
    <p>Самый болезненный сценарий — когда заказчик в одностороннем порядке отказывается от контракта из-за нарушений исполнителя. Помимо возврата аванса здесь добавляются репутационные и денежные последствия.</p>
    <ul>
      <li><b>Реестр недобросовестных поставщиков.</b> Сведения об исполнителе направляются в РНП, и на два года закрывается доступ к госзакупкам.</li>
      <li><b>Удержание неустойки.</b> Заказчик вправе удержать пени и штрафы из причитающихся сумм или предъявить их отдельно; механика расчёта — как в материале о <a href="/baza-znaniy/peni-i-shtrafy-po-44-fz/">пенях и штрафах по 44-ФЗ</a>.</li>
      <li><b>Нецелевое использование.</b> Если аванс израсходован не на цель контракта, добавляется ответственность по статье 15.14 КоАП РФ, а казначейство фиксирует нарушение режима целевых средств.</li>
    </ul>
    <p>При одностороннем отказе сумму к возврату обычно определяет заказчик исходя из неотработанного аванса, а спор о размере решается претензионно или в суде. До урегулирования остаток на счёте остаётся заблокированным, поэтому затягивать сверку невыгодно самому исполнителю.</p>

    <h2 id="soglashenie">Расторжение по соглашению сторон</h2>
    <p>Расторжение по соглашению сторон — предпочтительный путь, когда обе стороны заинтересованы выйти из контракта без конфликта. В соглашении прямо прописывают объём принятого, сумму возврата, реквизиты и срок. Это снимает разночтения и позволяет провести возврат быстро.</p>
    <p>Для исполнителя у этого варианта два плюса: нет автоматического попадания в РНП и есть возможность зафиксировать в соглашении, что претензий по качеству принятой части у заказчика нет. Для казначейского контура соглашение играет роль первичного документа: на его основании формируют распоряжение на возврат и затем закрывают счёт. Если соглашение составлено аккуратно — с точной суммой возврата и реквизитами, — финал проходит без отказов ТОФК.</p>

    <h2 id="soispolniteli">Соисполнители и незакрытые авансы</h2>
    <p>Когда по контракту работала кооперация, расторжение усложняется: авансы могли уйти соисполнителям, и часть из них на момент расторжения не отработана. Прежде чем возвращать остаток заказчику, эти средства нужно вернуть на головной целевой счёт.</p>
    <p>На практике порядок такой: головной исполнитель уведомляет соисполнителей о прекращении, фиксирует принятую от них часть, а неотработанные авансы они возвращают на лицевой счёт. Только после того, как все «хвосты» кооперации сведены, формируется итоговая сумма возврата заказчику. Если этот этап пропустить, остаток не обнулится, а казначейство справедливо откажет в закрытии счёта — деньги соисполнителей всё ещё числятся в контуре.</p>

    <h2 id="obespechenie">Что с обеспечением и КОО</h2>
    <p>Расторжение затрагивает и обеспечительные механизмы. Если исполнение контракта обеспечивалось <a href="/baza-znaniy/kaznacheyskoe-obespechenie-obyazatelstv/">казначейским обеспечением обязательств</a> или независимой гарантией, при расторжении они закрываются по своим правилам.</p>
    <table>
      <caption>Обеспечение при расторжении</caption>
      <tr><th>Механизм</th><th>Что происходит при расторжении</th></tr>
      <tr><td>Обеспечение исполнения контракта</td><td>Возврат поставщику при надлежащем расторжении; удержание неустойки при нарушениях</td></tr>
      <tr><td>Казначейское обеспечение обязательств (КОО)</td><td>Неиспользованное КОО отзывается; перечисление под него прекращается</td></tr>
      <tr><td>Обеспечение аванса</td><td>Закрывается после возврата неотработанного аванса источнику</td></tr>
    </table>
    <p>Поскольку обеспечение и движение целевых средств связаны, при расторжении их закрывают синхронно: сначала проводят взаиморасчёты и возврат, затем снимают обеспечительные обязательства. Рассинхрон приводит к ситуации, когда контракт «расторгнут», а обязательства по обеспечению формально висят.</p>

    <h2 id="raznica">Расторжение и завершение при исполнении</h2>
    <p>Финал контракта под сопровождением выглядит одинаково — возврат остатка и закрытие счёта, — но содержательно расторжение и штатное завершение отличаются.</p>
    <table>
      <caption>Расторжение и завершение при исполнении: что общего и в чём разница</caption>
      <tr><th>Параметр</th><th>Завершение при исполнении</th><th>Расторжение</th></tr>
      <tr><td>Повод</td><td>Контракт исполнен, работы приняты</td><td>Досрочное прекращение по ст. 95</td></tr>
      <tr><td>Доля возврата</td><td>Обычно небольшой остаток / экономия</td><td>Часто крупный неотработанный аванс</td></tr>
      <tr><td>Основной документ</td><td>Закрывающие акты, окончательный расчёт</td><td>Соглашение о расторжении / решение об отказе / суд</td></tr>
      <tr><td>Риски для исполнителя</td><td>Минимальные</td><td>РНП, неустойка, ответственность за нецелевое</td></tr>
      <tr><td>Финал в казначействе</td><td>Возврат остатка, закрытие счёта</td><td>Возврат аванса и остатка, закрытие счёта</td></tr>
