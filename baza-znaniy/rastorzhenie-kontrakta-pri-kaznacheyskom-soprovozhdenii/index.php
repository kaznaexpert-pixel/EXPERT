    <h2 id="chto-takoe">Что значит расторгнуть контракт под казначейское сопровождение</h2>
    <div class="answer reveal">
      <p class="lead-p">Расторжение контракта под казначейским сопровождением — это досрочное прекращение обязательств, при котором одновременно нужно закрыть финансовый контур: вернуть неотработанный аванс и неиспользованный остаток целевых средств источнику, отозвать или провести зависшие распоряжения и закрыть <a href="/baza-znaniy/licevoy-schet-71-kak-otkryt/">лицевой счёт 71</a>. Сам факт расторжения регулирует статья 95 Закона № 44-ФЗ, а судьбу денег на счёте — глава 24.4 Бюджетного кодекса и Правила казначейского сопровождения текущего года.<a class="fn" href="#ref-1" aria-label="Источник 1">[1]</a></p>
      <p>Ключевое отличие от обычного контракта в том, что деньги уже находятся под контролем казначейства. Перечисленный аванс лежит не на расчётном счёте исполнителя, а на целевом лицевом счёте в ТОФК, и распорядиться им произвольно нельзя. Поэтому при расторжении нельзя просто «разойтись»: пока остаток целевых средств не возвращён, а счёт не закрыт, контракт в казначейском контуре считается незавершённым, и это тянет за собой претензии заказчика, риски по обеспечению и блокировку расчётов.</p>
    </div>

    <h2 id="osnovaniya">Основания расторжения по 44-ФЗ</h2>
    <p>Статья 95 Закона № 44-ФЗ предусматривает три пути прекращения контракта. Под казначейским сопровождением каждый из них приводит к одному и тому же финансовому итогу — возврату остатка и закрытию счёта, но различается по процедуре и последствиям для сторон.</p>
    <ul>
      <li><b>По соглашению сторон.</b> Самый мягкий вариант: стороны фиксируют объём фактически исполненного, сумму к возврату и сроки. Реестр недобросовестных поставщиков при этом не грозит.</li>
      <li><b>Односторонний отказ от исполнения.</b> Заказчик или поставщик отказывается от контракта, если такое право предусмотрено контрактом и есть основания (существенное нарушение). Отказ заказчика из-за нарушений исполнителя — основание для включения в РНП.</li>
      <li><b>По решению суда.</b> Если согласия нет, спор о расторжении и взаиморасчётах решается судом; до вступления решения в силу остаток на счёте остаётся «замороженным».</li>
    </ul>
    <p>Какое бы основание ни сработало, первый практический вопрос — сколько аванса отработано, а сколько подлежит возврату. Ответ на него даёт не переписка сторон, а движение по целевому счёту, которое видно в <a href="/baza-znaniy/vypiska-iz-licevogo-scheta-kaznachejstva/">выписке из лицевого счёта</a>.</p>

