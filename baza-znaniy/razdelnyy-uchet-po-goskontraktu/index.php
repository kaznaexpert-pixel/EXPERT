    <h2 id="faq">Частые вопросы</h2>
    <div class="faq">
      <details open><summary>Что такое раздельный учёт по госконтракту?</summary><p>Это обособленный учёт доходов и расходов по каждому контракту, средства по которому подлежат казначейскому сопровождению. Он позволяет однозначно показать целевое использование средств по конкретному контракту.</p></details>
      <details><summary>Каким приказом установлен порядок учёта доходов и затрат при казначейском сопровождении?</summary><p>Порядок ведения учёта доходов и затрат участниками казначейского сопровождения по каждому госконтракту, договору или соглашению установлен приказом Минфина России от 10.12.2021 № 210н (действует в редакции от 27.06.2025). Для расширенного казначейского сопровождения требования к учёту дополнительно усилены приказом Федерального казначейства от 30.09.2025 № 12н.</p></details>
      <details><summary>Нужно ли вести раздельный учёт по каждому контракту?</summary><p>Да. При казначейском сопровождении юрлица и ИП ведут раздельный учёт результатов ФХД по каждому государственному (муниципальному) контракту, договору или соглашению в порядке, установленном Правительством РФ.</p></details>
      <details><summary>Какой штраф за неведение раздельного учёта?</summary><p>По статье 15.37.1 КоАП РФ: должностным лицам — 10 000–50 000 ₽; ИП — 5–10 % цены контракта, но не более 250 000 ₽; юрлицам — 5–10 % цены контракта, но не более 500 000 ₽.</p></details>
      <details><summary>С какой даты действует штраф по статье 15.37.1?</summary><p>Норма действует с 1 января 2026 года. Прежняя статья 15.37 КоАП (по ГОЗ) утратила силу с 1 марта 2025 года.</p></details>
      <details><summary>Чем раздельный учёт по госконтракту отличается от учёта по ГОЗ?</summary><p>Принцип общий — обособить доходы и расходы по контракту. Но нормативная база и формы разные: ГОЗ регулируется законодательством о гособоронзаказе, а обычный госконтракт под казначейское сопровождение — бюджетным законодательством и порядком Правительства.</p></details>
      <details><summary>Где закрепить методику раздельного учёта?</summary><p>В учётной политике организации: аналитика по контрактам, перечень прямых затрат, база распределения накладных расходов и регистры. Это первое, что проверяют контролёры.</p></details>
      <details><summary>Что проверяет казначейство в раздельном учёте?</summary><p>Наличие учёта и его корректность: соответствие затрат условиям контракта и смете, обоснованность распределения накладных, подтверждение затрат документами и применение закреплённой методики.</p></details>
      <details><summary>Каким актом установлен порядок раздельного учёта при расширенном казначейском сопровождении?</summary><p>Порядок раздельного учёта и документального обеспечения проверок при расширенном казначейском сопровождении обновлён приказом Федерального казначейства от 30.09.2025 № 12н.</p></details>
