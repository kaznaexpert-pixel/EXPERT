    <h2 id="goz-vs">Раздельный учёт по госконтракту и по ГОЗ — в чём разница</h2>
    <div class="answer reveal">
      <p>Это два разных режима, которые часто путают. Раздельный учёт по гособоронзаказу регулируется законодательством о ГОЗ (Закон № 275-ФЗ и профильные постановления) и имеет свои формы, правила распределения затрат и отдельную ответственность. Раздельный учёт по обычному госконтракту под казначейским сопровождением (например, по 44-ФЗ, по субсидиям, бюджетным инвестициям) опирается на бюджетное законодательство о казначейском сопровождении и порядок, установленный Правительством.</p>
      <p>Принцип у обоих один — обособить доходы и расходы по каждому контракту. Но нормативная база, формы и контролирующие процедуры различаются. Если у вас именно гособоронзаказ, ориентируйтесь на специальный материал — <a href="/baza-znaniy/razdelnyy-uchet-goz-275-fz/">«Раздельный учёт по ГОЗ: как вести, образец, штрафы»</a>. Эта же статья посвящена раздельному учёту по госконтрактам под казначейским сопровождением вне ГОЗ.</p>
    </div>

