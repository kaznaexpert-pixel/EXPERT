      <tr><td>Ресурсы контракта смешаны с прочей деятельностью</td><td>Одни материалы и специалисты на всех заказах без разделения</td><td>Позаказная аналитика: отдельные субсчета и аналитики по каждому контракту</td></tr>
    </table>
    <div class="answer reveal">
      <p>Ответственность за неведение раздельного учёта разобрана выше, в разделе о штрафах. Практическое правило: регистры должны собираться из текущего учёта нажатием кнопки, а не строиться вручную перед проверкой.</p>
    </div>

    <h2 id="keys">Пример из практики</h2>
    <div class="answer reveal">
      <p>Типовая ситуация: компания исполняет несколько контрактов под казначейским сопровождением и ведёт учёт «в целом по организации», планируя «разнести» затраты перед проверкой. При контрольном мероприятии выясняется, что выделить затраты по конкретному контракту невозможно, а часть накладных распределена без обоснованной базы. Результат — претензии по раздельному учёту и риск штрафа. На практике встречается и удачный сценарий: организация с самого старта заводит аналитику по каждому контракту и фиксирует методику в учётной политике — тогда проверка проходит без замечаний. Вывод: раздельный учёт выстраивают на входе в контракт, а не перед визитом казначейства.</p>
    </div>

    <p data-ctx="auto-ctx:otvetstvennost-za-narusheniya-goz">Для контрактов по гособоронзаказу действует отдельный состав — часть 11 статьи 7.30.3 КоАП РФ, тогда как при казначейском сопровождении применяется статья 15.37.1. Полный разбор административной и уголовной ответственности в сфере ГОЗ — в материале об <a href="/baza-znaniy/otvetstvennost-za-narusheniya-goz/">ответственности за нарушения в сфере ГОЗ</a>.</p>
    <p data-ctx="auto-ctx:nalogi-pri-kaznacheyskom-soprovozhdenii">Раздельный учёт не заменяет налоговый: как считаются НДС, налог на прибыль и УСН при работе через лицевой счёт, показано в статье <a href="/baza-znaniy/nalogi-pri-kaznacheyskom-soprovozhdenii/">о налогах при казначейском сопровождении</a>.</p>
    <p data-ctx="auto-ctx:shtrafy-pri-kaznacheyskom-soprovozhdenii-2026">С 1 января 2026 года за отсутствие раздельного учёта по контракту под сопровождением штрафуют по новой норме — см. <a href="/baza-znaniy/shtrafy-pri-kaznacheyskom-soprovozhdenii-2026/">штрафы при казначейском сопровождении (статьи 15.37.1 и 15.49 КоАП)</a>.</p>
    <p data-ctx="auto-ctx:kak-proyti-proverku-kaznachejstva">Раздельный учёт — одна из ключевых зон внимания при контроле, поэтому его наличие проверяют в первую очередь: как подготовиться, разобрано в материале <a href="/baza-znaniy/kak-proyti-proverku-kaznachejstva/">как пройти проверку казначейства</a>.</p>
    <p data-ctx="auto-ctx:kaznacheyskoe-soprovozhdenie-dlya-buhgaltera">Как раздельный учёт стыкуется с кодами расходования, сведениями и платёжной работой в единый процесс — показано в ролевом разборе <a href="/baza-znaniy/kaznacheyskoe-soprovozhdenie-dlya-buhgaltera/">казначейского сопровождения для бухгалтера</a>.</p>
    <p data-ctx="auto-ctx:vosstanovlenie-razdelnogo-ucheta-po-goskontraktu">Если учёт по контракту уже запущен или вёлся «котлом», его приводят в порядок задним числом — реконструируют регистры с даты начала контракта: как это сделать, разобрано в статье о <a href="/baza-znaniy/vosstanovlenie-razdelnogo-ucheta-po-goskontraktu/">восстановлении раздельного учёта по госконтракту</a>.</p>
