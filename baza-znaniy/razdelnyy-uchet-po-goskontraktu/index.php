    <h2 id="chto-takoe">Что такое раздельный учёт по госконтракту</h2>
    <div class="answer reveal">
      <p class="lead-p">Раздельный учёт по госконтракту — это организация бухгалтерского и управленческого учёта так, чтобы по каждому контракту можно было обособленно увидеть все доходы, прямые и накладные расходы, финансовый результат. При казначейском сопровождении это не «пожелание», а обязанность: средства по контракту целевые, и государство должно видеть, что каждый рубль израсходован именно на исполнение этого контракта, а не «смешан» с обычной деятельностью компании.</p>
      <p>Практический смысл прост: если деньги по нескольким контрактам и собственная выручка лежат «в общем котле», доказать целевое использование невозможно. Раздельный учёт разделяет потоки — по каждому контракту формируется собственная картина затрат, которая сверяется с условиями контракта и сведениями об операциях. Как заполняются сами сведения — в материале <a href="/baza-znaniy/svedeniya-ob-operaciyah-s-celevymi-sredstvami/">«Сведения об операциях с целевыми средствами»</a>.</p>
    </div>

    <h2 id="nuzhno">Нужно ли вести раздельный учёт по госконтракту</h2>
    <div class="answer reveal">
      <p>Да, если средства по контракту подлежат казначейскому сопровождению. В этом случае юридические лица и индивидуальные предприниматели обязаны вести раздельный учёт результатов финансово-хозяйственной деятельности по каждому государственному (муниципальному) контракту, договору или соглашению в порядке, установленном Правительством РФ. Условие о ведении раздельного учёта при этом включается в сам контракт<a class="fn" href="#ref-2" aria-label="Источник 2">[2]</a>.</p>
      <p>Если контракт под казначейское сопровождение не попадает, отдельной обязанности именно «раздельного учёта результатов ФХД» в смысле казначейского сопровождения не возникает. Поэтому первый шаг — определить, подпадает ли ваш контракт под сопровождение. Пороги и случаи мы разобрали в материале <a href="/baza-znaniy/kto-popadaet-pod-kaznacheyskoe-soprovozhdenie/">«Кто попадает под казначейское сопровождение»</a>.</p>
    </div>
    <div class="note"><b>Важно.</b> Обязанность привязана не к «любому госконтракту», а к казначейскому сопровождению средств. Нет сопровождения — нет и специального требования о раздельном учёте по правилам казначейского сопровождения.</div>

    <h2 id="osnova">На чём основан раздельный учёт при казначейском сопровождении</h2>
    <div class="answer reveal">
      <p>Базовая обязанность вытекает из бюджетного законодательства о казначейском сопровождении и Правил казначейского сопровождения (Постановление Правительства РФ от 24.11.2021 № 2024). Детали — как именно вести раздельный учёт доходов и затрат по каждому контракту — устанавливает <b>приказ Минфина России от 10.12.2021 № 210н</b> (действует в редакции от 27.06.2025): он задаёт порядок учёта доходов и затрат участников казначейского сопровождения в разрезе каждого госконтракта, договора или соглашения. Для расширенного казначейского сопровождения такой порядок обновлён приказом Федерального казначейства от 30.09.2025 № 12н, который усиливает требования к учёту и документальному обеспечению проверок<a class="fn" href="#ref-3" aria-label="Источник 3">[3]</a>.</p>
