    <h2 id="dokumenty">Документы и учётная политика</h2>
    <div class="answer reveal">
      <p>Раздельный учёт нужно закрепить в учётной политике организации: описать аналитику по контрактам, перечень прямых затрат, базу и порядок распределения накладных расходов, регистры, в которых формируются данные по каждому контракту. Учётная политика — это первое, что запросят при проверке: она показывает, что система раздельного учёта действительно выстроена, а не собирается «задним числом».</p>
      <p>Помимо политики, потребуются регистры раздельного учёта по контракту и первичные документы, подтверждающие затраты. Чем прозрачнее связка «контракт → затрата → документ → платёж», тем меньше вопросов у казначейства. Отсутствие или формальность учётной политики по раздельному учёту — частая причина претензий.</p>
    </div>

