    <p>Отдельно стоит обратить внимание на последний пункт: режим сопровождения «спускается» по цепочке. Головной исполнитель обязан включить аналогичное условие в договоры с соисполнителями, иначе средства не смогут двигаться по контуру. Это особенно важно при сложной кооперации.</p>

