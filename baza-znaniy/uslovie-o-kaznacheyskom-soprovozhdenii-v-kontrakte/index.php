    <h2 id="glavnoe">Когда условие о казначейском сопровождении включается в контракт</h2>
    <div class="answer reveal">
      <p class="lead-p">Условие о казначейском сопровождении включается в государственный контракт тогда, когда контракт попадает под сопровождение по бюджетному законодательству: его оплата идёт за счёт целевых средств, попавших в перечень по статье 5 Закона № 426-ФЗ о бюджете на 2026 год, либо это крупный аванс по правилам сопровождения. Если основание есть, заказчик обязан прописать сопровождение прямо в тексте контракта — это не право сторон, а требование закона. Сам режим установлен главой 24.4 Бюджетного кодекса.<a class="fn" href="#ref-1" aria-label="Источник 1">[1]</a></p>
      <p>Условие о сопровождении — это не одна строчка, а набор положений, которые меняют порядок расчётов по контракту: где открывается счёт, как маркируются платежи, что проверяет казначейство и какую отчётность ведёт исполнитель. Поэтому исполнителю важно прочитать эти пункты до подписания: они определяют, как он будет получать и тратить деньги по контракту. По сути, это инструкция к расчётам на весь срок исполнения, и игнорировать её — значит соглашаться с правилами вслепую.</p>
    </div>

