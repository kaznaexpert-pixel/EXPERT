    <p>Перечень целевых средств меняется каждый год вместе с законом о бюджете, поэтому формулировки в контракте всегда привязывают к актуальной норме. Подробно круг попадающих под сопровождение контрактов разобран в материале о том, <a href="/baza-znaniy/kto-popadaet-pod-kaznacheyskoe-soprovozhdenie/">кто попадает под казначейское сопровождение</a>.</p>

    <h2 id="sostav">Что должно быть в условии о сопровождении</h2>
    <p>Полноценное условие о казначейском сопровождении состоит из нескольких обязательных элементов. Их отсутствие или нечёткость — источник споров и отказов в санкционировании, поэтому проверять стоит каждый.</p>
    <table>
      <caption>Обязательные элементы условия о казначейском сопровождении в контракте</caption>
      <tr><th>Элемент</th><th>Что фиксирует</th></tr>
      <tr><td>Указание на сопровождение</td><td>Прямая запись, что расчёты по контракту подлежат казначейскому сопровождению</td></tr>
      <tr><td>Лицевой счёт в ТОФК</td><td>Обязанность исполнителя открыть лицевой счёт в территориальном органе казначейства</td></tr>
      <tr><td>Идентификатор</td><td>Указание идентификатора во всех договорах, платёжных и первичных документах</td></tr>
      <tr><td>Режим расходования</td><td>Оплата только на цель контракта после санкционирования операций</td></tr>
      <tr><td>Запрет перечислений</td><td>Запрет вывода целевых средств на обычные расчётные счета (с учётом норм 2026 года)</td></tr>
