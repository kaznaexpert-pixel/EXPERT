      <tr><td>Как проходит платёж</td><td>Свободно</td><td>После санкционирования операции</td></tr>
      <tr><td>Маркировка</td><td>Нет</td><td>Идентификатор во всех документах</td></tr>
      <tr><td>Отчётность по средствам</td><td>Нет</td><td>Сведения об операциях</td></tr>
      <tr><td>Кооперация</td><td>Свободные договоры</td><td>Условие о казначейском сопровождении в договорах с соисполнителями</td></tr>
