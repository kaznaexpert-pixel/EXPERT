      <details open><summary>Обязательно ли условие о казначейском сопровождении в контракте?</summary><p>Да, если контракт попадает под сопровождение по бюджетному законодательству. Тогда заказчик обязан прописать сопровождение в тексте контракта — это требование закона, а не выбор сторон.</p></details>
      <details><summary>Какие положения должны быть в условии?</summary><p>Указание на сопровождение, обязанность открыть лицевой счёт в казначействе, указание идентификатора во всех документах, расходование после санкционирования, отчётность и перенос условия в договоры с соисполнителями.</p></details>
      <details><summary>Где в контракте искать это условие?</summary><p>Обычно в разделе о порядке расчётов и оплате, а также в специальном разделе об особенностях исполнения. Иногда — в дополнительных условиях или приложениях к контракту.</p></details>
      <details><summary>Есть ли готовый образец формулировки?</summary><p>Структура условия типовая, но точная редакция зависит от контракта и заказчика. Обобщённый образец показывает, какие пункты должны быть; конкретные реквизиты заполняются по данным сделки.</p></details>
      <details><summary>Что меняет это условие для исполнителя?</summary><p>Деньги поступают на лицевой счёт в казначействе, каждый платёж санкционируется, во всех документах указывается идентификатор и ведётся отчётность по операциям.</p></details>
      <details><summary>Нужно ли переносить условие к соисполнителям?</summary><p>Да. Головной исполнитель включает условие о казначейском сопровождении в договоры с соисполнителями, иначе средства не смогут двигаться по контуру кооперации.</p></details>
      <details><summary>Что будет, если не открыть лицевой счёт?</summary><p>Оплата по контракту не пройдёт: при сопровождении расчёты идут только через лицевой счёт в казначействе. Поэтому счёт открывают сразу после заключения контракта.</p></details>
      <details><summary>Можно ли использовать прошлогодние формулировки?</summary><p>Структуру — да, но ссылки на нормы и перечень целевых средств нужно сверять с действующей редакцией на текущий год, иначе условие будет опираться на неактуальные положения.</p></details>
      <details><summary>Относится ли это к 223-ФЗ?</summary><p>Да, по тому же принципу: если договор по 223-ФЗ оплачивается целевыми средствами, условие о сопровождении включается аналогично. Закупки за счёт собственных средств заказчика под казначейское сопровождение не попадают.</p></details>
      <details><summary>Кто отвечает за корректность условия?</summary><p>Формулирует условие заказчик, но проверять его обязан и исполнитель — именно ему работать в режиме сопровождения. Спорные моменты лучше снять до подписания.</p></details>
