    <h2 id="chto-menyaet">Что условие меняет для исполнителя</h2>
    <p>Появление условия о сопровождении меняет привычную механику работы по контракту. Главное отличие — деньги приходят не на расчётный счёт в банке, а на <a href="/baza-znaniy/licevoy-schet-71-kak-otkryt/">лицевой счёт в казначействе</a>, и каждый платёж проходит предварительную проверку.</p>
    <table>
      <caption>Контракт без сопровождения и с условием о казначейском сопровождении</caption>
      <tr><th>Параметр</th><th>Обычный контракт</th><th>Контракт с условием о казначейском сопровождении</th></tr>
