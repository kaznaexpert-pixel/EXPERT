    <h3 id="uslovie">Этап 1. Условие о сопровождении в контракте</h3>
    <div class="answer reveal">
      <p>Сопровождение начинается не с похода в казначейство, а с текста контракта. Условие о казначейском сопровождении — обязательное: его включают в государственный контракт, договор или соглашение, а также в контракты исполнителей и соисполнителей. С 2025 года Бюджетный кодекс прямо закрепил, кто отвечает за включение условия: в госконтракт — заказчик, в договоры и контракты по цепочке кооперации — получатель средств или исполнитель.<a class="fn" href="#ref-1" aria-label="Источник 1">[1]</a> Если условия нет, средства нельзя довести через казначейство — а значит, контракт не исполнить в установленном режиме.</p>
    </div>

    <h3 id="schet">Этап 2. Лицевой счёт в территориальном органе казначейства</h3>
    <div class="answer reveal">
      <p>Целевые средства поступают не на банковский расчётный счёт, а на лицевой счёт участника казначейского сопровождения в ТОФК. Открывают его в «Электронном бюджете» при наличии электронной подписи. Это ключевое отличие режима: деньги «окрашены» и хранятся в казначейской системе. Как открыть такой счёт пошагово — в инструкции <a href="/baza-znaniy/licevoy-schet-71-kak-otkryt/">«Как открыть лицевой счёт 71»</a>, а чем казначейский счёт отличается от банковского — в разборе <a href="/baza-znaniy/kaznacheyskiy-schet/">«Казначейский счёт»</a>.</p>
    </div>

    <h3 id="igk">Этап 3. Идентификатор контракта и доведение средств</h3>
    <div class="answer reveal">
      <p>Каждому контракту под сопровождением присваивается идентификатор государственного контракта (ИГК) — 25-значный код, по которому казначейство «видит», к какому контракту относится каждый рубль. Под этот идентификатор средства доводятся на лицевой счёт. Что такое ИГК и как его указывать в документах — в материале <a href="/baza-znaniy/identifikator-gosudarstvennogo-kontrakta-igk/">«Идентификатор государственного контракта (ИГК)»</a>.</p>
    </div>

    <h3 id="sankcionirovanie">Этап 4. Санкционирование расходов</h3>
    <div class="answer reveal">
      <p>Это сердце порядка. Прежде чем деньги уйдут поставщику, участник подаёт в казначейство распоряжение и документы-основания. ТОФК проверяет, что суммы и направления использования из распоряжения соответствуют контракту и подтверждающим документам, что соблюдён режим лицевого счёта и указан корректный ИГК. Это документарный (формальный) контроль — без выезда и проверки факта поставки. Правила санкционирования установлены приказом Минфина № 214н в редакции от 27.06.2025.<a class="fn" href="#ref-3" aria-label="Источник 3">[3]</a> Подробно процедура и причины отказа разобраны в материале <a href="/baza-znaniy/poryadok-sankcionirovaniya-rashodov/">«Порядок санкционирования расходов»</a>.</p>
    </div>

    <h3 id="rezhim">Этап 5. Режим лицевого счёта: что нельзя</h3>
    <div class="answer reveal">
      <p>На средства, прошедшие сопровождение, действуют ограничения. По общему правилу статьи 242.23 запрещено вносить их в уставные капиталы других юрлиц, размещать на депозитах и в финансовых инструментах, а также перечислять на банковские счета — кроме прямо разрешённых направлений (оплата труда, фактически поставленные товары и услуги, аренда, связь, коммунальные платежи, налоги и ряд других). Именно эти запреты гарантируют целевое расходование.</p>
      <p>На 2026 год действует важная особенность переходного периода: федеральным законом от 28.11.2025 № 431-ФЗ продлено приостановление ряда запретов — в частности, в части открытия лицевых счетов поставщикам и запрета перечисления средств заказчикам на расчётные счета в банках. Это «упрощённый» режим, введённый ранее и продлённый до 1 января 2027 года.<a class="fn" href="#ref-4" aria-label="Источник 4">[4]</a> Поэтому конкретные ограничения по своему контракту в 2026 году стоит сверять с действующей редакцией статьи 242.23 и условиями соглашения.</p>
    </div>

    <h3 id="uchet">Этап 6. Раздельный учёт</h3>
    <div class="answer reveal">
      <p>Участник казначейского сопровождения обязан вести раздельный учёт результатов финансово-хозяйственной деятельности по каждому контракту или соглашению. Это позволяет подтвердить, что затраты относятся именно к целевым средствам. Как организовать такой учёт — в разборе <a href="/baza-znaniy/razdelnyy-uchet-po-goskontraktu/">«Раздельный учёт по госконтракту»</a>, а оформляющий его документ — в материале <a href="/baza-znaniy/uchetnaya-politika-razdelnyy-uchet-goz/">«Учётная политика по раздельному учёту ГОЗ»</a>.</p>
    </div>

    <h3 id="otchetnost">Этап 7. Отчётность по целевым средствам</h3>
    <div class="answer reveal">
      <p>Завершает порядок отчётность: участник формирует сведения об операциях с целевыми средствами — документ, который отражает движение и остатки. Как его заполнить — в инструкции <a href="/baza-znaniy/svedeniya-ob-operaciyah-s-celevymi-sredstvami/">«Сведения об операциях с целевыми средствами»</a>.</p>
