    <h2 id="keys">Пример из практики</h2>
    <div class="answer reveal">
      <p>Типовая ситуация: организация выиграла крупный контракт с авансом и считала, что работает как обычно — через расчётный счёт. Об условии казначейского сопровождения вспомнили только при попытке получить аванс, электронной подписи и лицевого счёта ещё не было, и старт исполнения сдвинулся. После того как сначала оформили подпись и счёт в ТОФК, уточнили ИГК и настроили раздельный учёт, расходы пошли через санкционирование без задержек. На практике помогает простое правило: порядок казначейского сопровождения начинается не с денег, а с условия в контракте — и готовиться к нему нужно заранее. Это обобщённый пример; конкретный порядок зависит от вида средств и условий контракта.</p>
    </div>

