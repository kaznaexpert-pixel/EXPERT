    <h2 id="korotkiy-otvet">Короткий ответ: это разные вещи</h2>
    <p>Казначейское обслуживание и казначейское сопровождение путают из-за похожих слов, но это разные понятия. <b>Обслуживание</b> — это проведение и учёт операций по казначейским счетам, то есть сама инфраструктура расчётов. <b>Сопровождение</b> — это режим контроля за целевым использованием конкретных средств по контракту или субсидии.</p>
    <p>Короткая формула: обслуживание отвечает на вопрос «как проходят платежи», сопровождение — «за какими средствами следят и насколько строго». Ниже — что стоит за каждым термином и как они соотносятся на практике.</p>

    <h2 id="chto-takoe-obsluzhivanie">Что такое казначейское обслуживание</h2>
    <p>Казначейское обслуживание — это осуществление и отражение Федеральным казначейством операций с денежными средствами на казначейских счетах. По сути это техническая функция: ведение счетов, проведение и учёт платежей в системе казначейских платежей. Основы закреплены статьёй 242.13 Бюджетного кодекса, а обслуживание операций со средствами участников казначейского сопровождения — отдельной статьёй 242.19-1.</p>
    <p>Обслуживание есть везде, где деньги проходят через казначейские счета: через него идут расчёты бюджетов и операции участников сопровождения. Это «трубопровод», а не контроль содержания платежа. Подробнее о самой инфраструктуре — в разборе <a href="/baza-znaniy/sistema-kaznacheyskih-platezhey/">системы казначейских платежей</a> и <a href="/baza-znaniy/edinyy-kaznacheyskiy-schet/">единого казначейского счёта</a>.</p>

    <h2 id="chto-takoe-soprovozhdenie">Что такое казначейское сопровождение</h2>
    <p>Казначейское сопровождение — это режим контроля за целевым расходованием конкретных средств, установленный главой 24.4 Бюджетного кодекса. Под него попадают целевые средства: авансы по государственным контрактам, субсидии, бюджетные инвестиции, гособоронзаказ. Казначейство не просто проводит платёж, а проверяет каждую операцию на соответствие цели контракта и подтверждающим документам — это <a href="/baza-znaniy/poryadok-sankcionirovaniya-rashodov/">санкционирование</a>.</p>
    <p>То есть сопровождение — это надстройка контроля поверх обслуживания: деньги идут через те же казначейские счета, но с дополнительной проверкой целевого характера. Что это такое в целом и кому нужно — в базовом разборе <a href="/baza-znaniy/chto-takoe-kaznacheyskoe-soprovozhdenie/">казначейское сопровождение: что это и как работает</a>.</p>

