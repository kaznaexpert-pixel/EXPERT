    <h2 id="kak-svyazany">Как они связаны на практике</h2>
    <p>Обслуживание и сопровождение не противоречат друг другу, а работают слоями. Любая операция по казначейскому счёту физически проходит через обслуживание. Если же средства целевые и подпадают под сопровождение, к обслуживанию добавляется контроль: проверка оснований платежа, целевого назначения, раздельного учёта.</p>
    <p>Поэтому фраза «контракт на казначейском обслуживании» некорректна, если речь про контроль целевых средств — правильно «на казначейском сопровождении». А «обслуживание» уместно, когда говорят о самом факте прохождения операций через казначейские счета.</p>

    <h2 id="kak-opredelit">Что применяется к вашему контракту</h2>
    <p>Определить просто: смотрите, есть ли в контракте условие о казначейском сопровождении.</p>
    <ul>
      <li>Есть условие о сопровождении и требование открыть лицевой счёт — работает режим сопровождения (со всем контролем), а расчёты по нему идут через обслуживание.</li>
      <li>Нет условия о сопровождении, но расчёты идут через казначейский счёт — это обслуживание без дополнительного целевого контроля.</li>
      <li>Обычный контракт без казначейских счетов — ни то, ни другое к вам не применяется.</li>
    </ul>
    <p>Если сомневаетесь, участник вы или нет и что именно применяется, посмотрите разбор про <a href="/baza-znaniy/uchastniki-kaznacheyskogo-soprovozhdeniya/">участников казначейского сопровождения</a>.</p>

