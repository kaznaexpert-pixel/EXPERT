    <h2 id="faq">Частые вопросы</h2>
    <div class="faq">
      <details open><summary>Чем казначейское обслуживание отличается от казначейского сопровождения?</summary><p>Обслуживание — это проведение и учёт операций по казначейским счетам (техническая инфраструктура расчётов). Сопровождение — режим контроля за целевым расходованием конкретных средств по главе 24.4 Бюджетного кодекса, с санкционированием каждого платежа. Обслуживание отвечает на вопрос «как проходят платежи», сопровождение — «за какими средствами следят».</p></details>
      <details><summary>Это одно и то же?</summary><p>Нет. Оба выполняет Федеральное казначейство, но обслуживание есть всегда при расчётах через казначейские счета, а сопровождение включается только для целевых средств, когда это предусмотрено контрактом.</p></details>
      <details><summary>Что шире — обслуживание или сопровождение?</summary><p>Обслуживание шире: через него проходят все операции по казначейским счетам. Сопровождение — это дополнительный слой целевого контроля поверх обслуживания для отдельных средств.</p></details>
      <details><summary>Мой контракт «на казначейском обслуживании» — это сопровождение?</summary><p>Если по контракту нужно открыть лицевой счёт, вести раздельный учёт и проходить санкционирование, речь о сопровождении. «Обслуживание» корректно только про сам факт прохождения операций через казначейские счета.</p></details>
      <details><summary>Какие статьи Бюджетного кодекса это регулируют?</summary><p>Казначейское обслуживание — статьи 242.13 и 242.19-1; казначейское сопровождение — глава 24.4 (статья 242.23 и далее) Бюджетного кодекса.</p></details>
      <details><summary>Создаёт ли обслуживание обязанности для исполнителя?</summary><p>Само по себе — нет. Дополнительные обязанности (лицевой счёт, раздельный учёт, санкционирование) возникают именно при сопровождении целевых средств.</p></details>
      <details><summary>Как понять, что применяется ко мне?</summary><p>Посмотрите контракт: есть ли условие о казначейском сопровождении и требование открыть лицевой счёт. Есть — работает сопровождение; нет, но расчёты через казначейский счёт — только обслуживание.</p></details>
