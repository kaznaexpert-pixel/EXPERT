    <h2 id="proverki">Четыре блока проверок расширенного казначейского сопровождения</h2>
    <h3>1. Фактическая поставка товаров, работ, услуг</h3>
    <p>Операции по лицевому счёту проводятся после проверки соответствия фактически поставленных товаров (выполненных работ, оказанных услуг) информации в контракте и документах-основаниях. Закон прямо допускает использование фото- и видеотехники: казначейство фиксирует, что оборудование реально поставлено, работы реально выполнены. Процедура идёт по регламенту, утверждённому Федеральным казначейством.<a class="fn" href="#ref-1" aria-label="Источник 1">[1]</a></p>
    <h3>2. Раздельный учёт и фактические затраты</h3>
    <p>Проверяется не только наличие раздельного учёта результатов финансово-хозяйственной деятельности, но и соответствие фактических затрат данным этого учёта — в информационных системах бухгалтерского и управленческого учёта участника, в первичных документах и в расходной декларации. Как выстроить учёт, чтобы пройти такую сверку, — в разборах <a href="/baza-znaniy/razdelnyy-uchet-goz-275-fz/">раздельного учёта по ГОЗ</a> и <a href="/baza-znaniy/uchetnaya-politika-razdelnyy-uchet-goz/">учётной политики</a>.<a class="fn" href="#ref-1" aria-label="Источник 1">[1]</a></p>
    <h3>3. Экономическая обоснованность затрат</h3>
    <p>Новелла 177-ФЗ: казначейство оценивает, обоснованы ли затраты по контракту, — по порядку ФК и правилам экономического обоснования затрат, установленным Правительством. Это шаг от формального контроля к содержательному аудиту цены исполнения.<a class="fn" href="#ref-1" aria-label="Источник 1">[1]</a></p>
    <h3>4. Контроль вывода средств</h3>
    <p>Перевод денег с лицевого счёта на банковские счета участника проводится после направления госзаказчиком в казначейство уведомления о полном исполнении контракта. Заработанная прибыль «выходит» из казначейского контура только после закрытия всего контракта.<a class="fn" href="#ref-1" aria-label="Источник 1">[1]</a></p>

