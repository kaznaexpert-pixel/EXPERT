    <h2 id="faq">Частые вопросы</h2>
    <div class="faq">
      <details open><summary>Что такое расширенное казначейское сопровождение простыми словами?</summary><p>Это усиленный режим контроля бюджетных денег: казначейство проводит платежи только после проверки, что товары реально поставлены, учёт ведётся раздельно, затраты подтверждены документами и экономически обоснованы.</p></details>
      <details><summary>Чем расширенное казначейское сопровождение отличается от обычного?</summary><p>Обычное сопровождение — контроль по документам. Расширенное добавляет проверки по существу: фактическую поставку (вплоть до фото/видео), сверку затрат с раздельным учётом и расходной декларацией, оценку обоснованности затрат и ограничение на вывод средств до полного исполнения контракта.</p></details>
      <details><summary>Кто решает, что контракт под расширенным казначейским сопровождением?</summary><p>Случаи применения определяются правовым актом Правительства РФ (п. 1 ст. 242.24 БК). Режим фиксируется в условиях контракта.</p></details>
      <details><summary>Может ли казначейство выехать на объект и снимать на видео?</summary><p>Да. Статья 242.24 БК прямо допускает проверку соответствия фактически поставленных товаров и выполненных работ с использованием фото- и видеотехники, по регламенту Федерального казначейства.</p></details>
      <details><summary>Что такое расходная декларация и зачем она нужна?</summary><p>Это документ о структуре затрат по контракту. При расширенном казначейском сопровождении казначейство сверяет с ней данные раздельного учёта и первичных документов — расхождения ведут к отказу в операции.</p></details>
      <details><summary>Когда можно вывести деньги на свой расчётный счёт?</summary><p>После того как госзаказчик направит в казначейство уведомление о полном исполнении контракта. До этого средства работают только внутри казначейского контура.</p></details>
      <details><summary>Проверяет ли казначейство цены и затраты?</summary><p>Да, с поправок 177-ФЗ (2024) проверяется экономическая обоснованность затрат — по порядку, утверждённому ФК, и правилам экономического обоснования затрат от Правительства. Порядок закреплён в <a href="/baza-znaniy/normativnaya-baza/pp-2024-pravila-ks/">Правилах казначейского сопровождения (ПП № 2024)</a>.</p></details>
      <details><summary>Применяется ли расширенное казначейское сопровождение на региональном уровне?</summary><p>Да, финансовые органы субъектов РФ и муниципалитетов вправе осуществлять расширенное сопровождение средств своего уровня в случаях, определённых Правительством (п. 3 ст. 242.24 БК).</p></details>
      <details><summary>Сколько времени занимают проверки?</summary><p>Дольше стандартного санкционирования: к документарному контролю добавляются содержательные проверки. Точные сроки зависят от регламентов ФК и сложности контракта — закладывайте запас в график оплат.</p></details>
      <details><summary>Как подготовиться к расширенному сопровождению?</summary><p>Настроить раздельный учёт с первого дня, привести расходную декларацию в соответствие с калькуляцией и первичкой, собирать обоснования затрат и планировать кассу с учётом вывода средств после полного исполнения.</p></details>
    </div>

