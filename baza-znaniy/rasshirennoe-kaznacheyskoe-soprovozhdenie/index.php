    <h2 id="chto-takoe">Что такое расширенное казначейское сопровождение</h2>
    <div class="answer reveal">
      <p class="lead-p">Расширенное казначейское сопровождение — это усиленный режим контроля целевых средств по статье 242.24 БК РФ. К стандартным требованиям казначейского сопровождения добавляются проверки до проведения операций: соответствие фактически поставленных товаров и выполненных работ контракту, ведение раздельного учёта, соответствие затрат первичным документам и расходной декларации, экономическая обоснованность затрат.<a class="fn" href="#ref-1" aria-label="Источник 1">[1]</a></p>
      <p>Если обычное сопровождение — это контроль по документам, то расширенное — контроль по существу: казначейство сверяет бумаги с реальностью, в том числе выходя «в поле» с фото- и видеофиксацией. Для подрядчика это означает, что каждый платёж зависит не только от корректности комплекта документов, но и от состояния дел на объекте и в учёте.</p>
    </div>
    <p>Режим введён Федеральным законом от 01.07.2021 № 244-ФЗ вместе со всей главой 24.4 БК РФ и с тех пор ужесточался: закон от 13.07.2024 № 177-ФЗ добавил проверку экономической обоснованности затрат и расходную декларацию, а закон от 24.06.2025 № 158-ФЗ уточнил требования к данным раздельного учёта в информационных системах участников.<a class="fn" href="#ref-1" aria-label="Источник 1">[1]</a></p>

