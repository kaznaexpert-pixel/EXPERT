    <h2 id="glossary">Глоссарий</h2>
    <dl class="gloss">
      <div><dt>Расширенное казначейское сопровождение</dt><dd>Режим контроля по ст. 242.24 БК РФ с проверками фактического исполнения, учёта и обоснованности затрат до проведения операций.</dd></div>
      <div><dt>Расходная декларация</dt><dd>Документ участника казначейского сопровождения о структуре затрат по контракту; сверяется с раздельным учётом и первичкой.</dd></div>
      <div><dt>Проверка фактической поставки</dt><dd>Сверка реально поставленных товаров (работ, услуг) с контрактом и документами, в том числе с фото- и видеофиксацией.</dd></div>
      <div><dt>Экономическая обоснованность затрат</dt><dd>Соответствие затрат по контракту правилам обоснования, установленным Правительством (проверяется с 2024 года).</dd></div>
      <div><dt>Уведомление о полном исполнении</dt><dd>Документ госзаказчика, после которого допускается перевод средств с лицевого счёта на банковские счета участника.</dd></div>
