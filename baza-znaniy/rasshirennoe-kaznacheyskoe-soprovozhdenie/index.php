    <p>Тренд читается однозначно: контроль смещается от формальной проверки документов к содержательной проверке исполнения и цены. Планируя долгий контракт, исходите из того, что требования к учёту будут только расти.</p>

    <h2 id="deklaraciya">Расходная декларация: новый обязательный документ</h2>
    <p>Расходная декларация — документ, в котором участник раскрывает структуру затрат по контракту. При расширенном сопровождении именно с ней казначейство сверяет данные раздельного учёта и первички. Практический смысл: декларация должна «биться» с учётными системами до копейки, а структура затрат — соответствовать калькуляции цены контракта. Расхождения между декларацией, первичкой и регистрами учёта — типовая причина отказов в проведении операций.</p>

    <h2 id="vyvod-sredstv">Вывод средств: главное практическое ограничение</h2>
    <p>В обычном режиме участник может в установленных случаях переводить средства на свой расчётный счёт (например, возмещение произведённых расходов или прибыль по этапам — если это допускает режим счёта). В расширенном режиме планка выше: до уведомления о полном исполнении контракта деньги остаются в казначейском контуре. Для кассового планирования это означает, что прибыль по долгому контракту «разморозится» только в конце — финансировать текущую деятельность нужно из других источников.</p>

    <h2 id="podgotovka">Как подготовиться к расширенному казначейскому сопровождению: чек-лист</h2>
    <ul>
      <li>зафиксировать в учётной политике раздельный учёт по контракту и настроить аналитику в учётной системе до первого платежа;</li>
      <li>выстроить соответствие «калькуляция цены → расходная декларация → первичка → регистры учёта» — единая структура статей затрат;</li>
      <li>назначить ответственного за подготовку к проверкам фактической поставки (доступ на объект, комплект исполнительной документации, готовность к фото/видеофиксации);</li>
      <li>собирать обосновывающие документы по затратам (коммерческие предложения, расчёты, нормы) — под проверку экономической обоснованности;</li>
      <li>планировать кассу с учётом того, что вывод средств — после полного исполнения контракта;</li>
      <li>закладывать в график оплат время на проверки сверх стандартного санкционирования.</li>
    </ul>

