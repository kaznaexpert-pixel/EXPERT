    <h2 id="kogda">Когда применяется расширенное казначейское сопровождение</h2>
    <p>Перечень случаев не «зашит» в кодекс: расширенное сопровождение применяется к средствам по государственным контрактам, договорам и соглашениям, определённым правовым актом Правительства (п. 1 ст. 242.24 БК РФ). На практике под усиленный режим попадают чувствительные для бюджета истории: отдельные направления гособоронзаказа, крупные стройки, контракты с повышенными рисками. С 2024 года финансовые органы субъектов и муниципалитетов тоже вправе вести расширенное сопровождение средств своего уровня — в случаях, определённых Правительством (п. 3 ст. 242.24).<a class="fn" href="#ref-1" aria-label="Источник 1">[1]</a></p>
    <p>Узнать, что контракт под расширенным казначейским сопровождением, можно из его условий: режим фиксируется в контракте вместе с обязанностью открыть лицевой счёт и соблюдать порядок проверок. Если в контракте есть отсылки к «проверке фактической поставки» и «расходной декларации» — это оно.</p>

