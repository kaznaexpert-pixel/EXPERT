    <h3 id="ogovorki-blankov">Какие две оговорки есть у самих бланков</h3>
    <p>Отдельно стоит держать в голове две оговорки самих бланков. Первая: административно-управленческие расходы включаются в зависимости от того, как построена учётная политика организации, — и если по учётной политике они относятся на финансовый результат контракта, статья «Общехозяйственные затраты» (строка 0900) не применяется.<a class="fn" href="#ref-1" aria-label="Источник 1">[1]</a> Вторая: часть строк заполняется только при определении цены на научно-техническую продукцию, а также на работы по ремонту, сервисному обслуживанию и утилизации.<a class="fn" href="#ref-1" aria-label="Источник 1">[1]</a> Как закрепить методику, чтобы она не разъезжалась от контракта к контракту, — в разборе <a href="/baza-znaniy/uchetnaya-politika-razdelnyy-uchet-goz/">учётной политики под раздельный учёт ГОЗ</a>.</p>

    <h2 id="plan">Плановая калькуляция: что важно в форме № 2</h2>
    <p>Плановая калькуляция — центральный документ комплекта при затратном методе. Три её особенности задают качество всего комплекта.</p>
    <h3 id="tri-kolonki">Какие три графы заполняют в плановой калькуляции</h3>
    <p><b>Три колонки вместо одной.</b> В форме предусмотрены отдельные графы: плановые затраты, ранее согласованные заказчиком при формировании ориентировочной (уточняемой) или возмещающей издержки цены; то, что предлагает организация-поставщик; и то, что принято заказчиком. Заполнение только «своей» колонки — типовая причина возврата: проверяющему нужна сопоставимость.</p>
    <h3 id="stroka-1700">Что требует строка 1700 формы № 2</h3>
    <p><b>Раскрытие себестоимости.</b> Строка 1700 требует разложить себестоимость на привнесённые (покупные) и собственные затраты. От их соотношения считается предельная прибыль по правилу «не более 1 % привнесённых плюс не более 25 % собственных» — детально в разборе <a href="/baza-znaniy/normy-pribyli-goz/">норм прибыли по гособоронзаказу</a>.</p>
    <h3 id="analogovyy-podhod">Какая форма применяется при аналоговом подходе</h3>
    <p><b>Аналоговый подход — другая форма.</b> Если цена формируется с использованием аналогового подхода, плановая калькуляция представляется не по форме № 2, а по форме № 2А (2Ад), которая объединяет плановую калькуляцию на продукцию и отчётную калькуляцию на аналог.<a class="fn" href="#ref-1" aria-label="Источник 1">[1]</a> Какие вообще бывают виды цен и методы их определения — в статье о <a href="/baza-znaniy/vidy-cen-goz/">видах цен на продукцию ГОЗ</a>.</p>

    <h2 id="fakt">Отчётная калькуляция: что важно в форме № 3</h2>
    <p>Отчётная калькуляция — это план и факт рядом, построчно. Именно она превращает разговор о цене из спора в арифметику.</p>
    <p class="note">Косвенные затраты в цене контракта считаются отдельно: чем административно-управленческие расходы отличаются от общехозяйственных затрат и по какой базе их распределяют — в разборе <a href="/baza-znaniy/aur-i-prochie-zatraty-goz/">АУР и прочих затрат в гособоронзаказе &rarr;</a>.</p>
    <h3 id="pervaya-postavka">Нужна ли отчётная калькуляция при первой поставке</h3>
    <p><b>Первая поставка — без отчётной калькуляции.</b> Сноска к форме прямо указывает: сведения приводятся за последний отчётный период по исполненному контракту, если продукция ранее поставлялась; при отсутствии поставки ранее отчётная калькуляция не представляется.<a class="fn" href="#ref-1" aria-label="Источник 1">[1]</a> Это снимает частый вопрос новых исполнителей, которым «требуют факт» по продукции, которую они ещё не выпускали.</p>
    <h3 id="dlinnyy-cikl">Как заполнять форму при цикле производства дольше года</h3>
    <p><b>Длинный цикл — разбивка по годам.</b> Если технологический цикл производства превышает год либо год начала производства не совпадает с годом окончания производства и поставки (или завершения отдельных этапов, если контрактом такие этапы предусмотрены), сведения представляются по каждому году выполнения работ.<a class="fn" href="#ref-1" aria-label="Источник 1">[1]</a></p>
    <h3 id="otkuda-fakt">Откуда берутся цифры колонки «Факт»</h3>
