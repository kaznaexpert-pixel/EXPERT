    <h2 id="faq">Частые вопросы</h2>
    <div class="faq"><details open><summary>Чем плановая калькуляция отличается от отчётной?</summary><p>Плановая калькуляция (форма № 2) составляется при формировании цены и показывает ожидаемые затраты на предстоящий период — в шапке стоит «на ____ г.». Отчётная (форма № 3 (3д)) составляется после исполнения контракта или этапа, содержит колонки «План» и «Факт» и опирается на данные раздельного учёта. Структура статей затрат у обеих форм одинаковая.</p></details>
<details><summary>Кто подписывает отчётную калькуляцию?</summary><p>По бланку формы № 3 (3д) — военный представитель, главный бухгалтер организации-поставщика (при наличии) и руководитель её экономической службы; печать ставится при наличии. Плановую калькуляцию по форме № 2 подписывают руководители экономических служб заказчика и организации-поставщика.</p></details>
<details><summary>Нужна ли отчётная калькуляция, если продукция выпускается впервые?</summary><p>Нет. Сноска к форме № 3 указывает, что сведения приводятся за последний отчётный период по исполненному контракту, если продукция ранее поставлялась; при отсутствии поставки ранее отчётная калькуляция не представляется.</p></details>
<details><summary>Как заполнять калькуляцию, если производство идёт больше года?</summary><p>При продолжительности технологического цикла более одного года либо когда год начала производства не совпадает с годом окончания производства и поставки (или завершения отдельных этапов, предусмотренных контрактом), сведения представляются по каждому году выполнения работ.</p></details>
<details><summary>В какой срок нужна отчётная калькуляция для перевода цены?</summary><p>Отдельного срока «на калькуляцию» нет, ориентир задаёт сама процедура: по Положению № 1465 фиксированная цена устанавливается не позднее чем за два месяца до окончания поставки продукции или завершения отдельного этапа. Отчётные данные и уточнённые расчёты собирают с запасом к этому сроку.</p></details>
<details><summary>Что делать, если фактические затраты превысили плановые?</summary><p>Превышение принимается только с документальным обоснованием: рост цен поставщиков, изменение технологии, иные подтверждённые причины. Необъяснённое превышение в цену не включат, и разница ляжет на прибыль предприятия. Причины расхождений раскрываются в пояснительной записке построчно.</p></details></div>

