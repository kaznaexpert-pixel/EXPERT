    <h2 id="rashozhdeniya">Что бывает при расхождении плана и факта</h2>
    <p>Расхождение само по себе не нарушение — производство не бывает точным до рубля. Проблемой оно становится, когда его нечем объяснить.</p>
    <ul>
      <li><b>Факт ниже плана.</b> Экономия по существенным строкам — повод пересмотреть цену вниз при её переводе в фиксированную. Именно поэтому «запас» в плановой калькуляции редко доживает до закрытия контракта.</li>
      <li><b>Факт выше плана.</b> Превышение принимается только с обоснованием: рост цен поставщиков, изменение технологии, документально подтверждённые причины. Необъяснённое превышение просто не включат в цену — разница останется на предприятии.</li>
      <li><b>Факт не бьётся с учётом.</b> Самый тяжёлый случай: цифры отчётной калькуляции не выводятся из регистров. Это ставит под сомнение весь комплект и легко перерастает в контрольное мероприятие.</li>
      <li><b>Расхождение внутри комплекта.</b> Итог расшифровки не равен строке калькуляции, трудоёмкость не соответствует зарплате, нормативы в форме № 22 отличаются от применённых. Такие ошибки находят первыми — сквозная сверка перед сдачей закрывает их полностью.</li>
    </ul>
    <p>Как выглядит сквозная сверка на конкретных цифрах и откуда берётся каждая строка калькуляции, показано в разборе <a href="/baza-znaniy/obrazec-zapolneniya-rkm/">образца заполнения РКМ</a>.</p>

