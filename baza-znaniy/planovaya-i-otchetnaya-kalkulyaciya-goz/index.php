    <h3 id="kto-podpisyvaet">Кто подписывает плановую и отчётную калькуляцию</h3>
    <p>Обратите внимание на строку с подписями: это не формальность. Плановую калькуляцию визируют экономисты, отчётную — военный представитель и главный бухгалтер. Подпись главбуха означает, что цифры факта сверены с бухгалтерским учётом, а не собраны в отдельной таблице «для военпреда».</p>

