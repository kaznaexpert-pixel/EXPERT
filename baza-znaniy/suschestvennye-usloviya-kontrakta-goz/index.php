    <h2 id="keys">Пример из практики</h2>
    <div class="answer reveal">
      <p>Типовая ситуация: исполнитель заключает контракт по ГОЗ и начинает рассчитываться с поставщиком с обычного расчётного счёта, не открыв отдельный счёт и не перенеся условия в договор с соисполнителем. Платежи не проходят по режиму, а заказчик фиксирует нарушение существенных условий. После того как открыли отдельный счёт, проставили ИГК и привели договоры кооперации в соответствие, расчёты пошли штатно. На практике помогает простое правило: до первого платежа сверить контракт по чек-листу существенных условий и открыть нужный счёт заранее, а не в момент, когда оплата уже горит.</p>
    </div>

    <p data-ctx="auto-ctx:uslovie-o-kaznacheyskom-soprovozhdenii-v-kontrakte">Если контракт идёт под казначейским сопровождением, в нём появляется отдельное <a href="/baza-znaniy/uslovie-o-kaznacheyskom-soprovozhdenii-v-kontrakte/">условие о казначейском сопровождении</a> с обязательным набором положений — его проверяют до подписания.</p>
    <p data-ctx="auto-ctx:izmenenie-sushchestvennyh-usloviy-kontrakta-44-fz">Менять существенные условия контракта при исполнении по общему правилу нельзя; допустимые случаи и правило десяти процентов разобраны в материале об <a href="/baza-znaniy/izmenenie-sushchestvennyh-usloviy-kontrakta-44-fz/">изменении существенных условий контракта по 44-ФЗ</a>.</p>
    <div class="takeaways">
      <h2>Что важно запомнить</h2>
      <ol>
        <li>Существенные условия по ГОЗ шире, чем у обычного контракта: к цене и срокам добавляются счета, ИГК, сопровождение и кооперация.</li>
        <li>Расчёты ведутся только через отдельный счёт с режимом использования средств.</li>
        <li>ИГК указывают в номере контракта, платежах и договорах с соисполнителями.</li>
        <li>Сопровождение бывает банковским (уполномоченный банк) или казначейским (лицевой счёт в ТОФК).</li>
        <li>Перед подписанием контракт проверяют по чек-листу существенных условий.</li>
      </ol>
