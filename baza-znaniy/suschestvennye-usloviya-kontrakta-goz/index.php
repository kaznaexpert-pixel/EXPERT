    <h2 id="faq">Частые вопросы</h2>
    <div class="faq">
      <details open><summary>Какие условия контракта по ГОЗ являются существенными?</summary><p>Предмет, цена и её вид, идентификатор государственного контракта (ИГК), условие об отдельном счёте и режиме его использования, форма сопровождения (банковское или казначейское), обязанности по кооперации, сроки и порядок приёмки.</p></details>
      <details><summary>Каким законом регулируется контракт по ГОЗ?</summary><p>Общие условия — Федеральным законом № 44-ФЗ (статья 34), специальные требования гособоронзаказа — Федеральным законом от 29.12.2012 № 275-ФЗ «О государственном оборонном заказе». Часть условий приходит из типовых условий контрактов ГОЗ.</p></details>
      <details><summary>Зачем в контракте ГОЗ отдельный счёт?</summary><p>Чтобы обеспечить прослеживаемость средств: расчёты по контракту идут только через отдельный счёт с режимом использования, а назначение каждого платежа контролируется банком или казначейством.</p></details>
      <details><summary>Чем банковское сопровождение ГОЗ отличается от казначейского?</summary><p>При банковском сопровождении счёт открывается в уполномоченном банке, который контролирует расчёты. При казначейском — лицевой счёт в территориальном органе казначейства с санкционированием операций. По умолчанию для ГОЗ применяется банковское сопровождение, для отдельных контрактов — казначейское.</p></details>
      <details><summary>Нужно ли указывать ИГК в контракте по ГОЗ?</summary><p>Да. Идентификатор государственного контракта указывают в номере контракта, в платёжных документах, во внутренних распоряжениях исполнителя и в договорах с соисполнителями. В ГОЗ применяется 25-значный идентификатор.</p></details>
      <details><summary>Что будет, если нарушить режим отдельного счёта?</summary><p>Платежи не пройдут по режиму использования счёта, а нарушение существенных условий контракта может повлечь претензии заказчика и ответственность исполнителя.</p></details>
      <details><summary>Должны ли соисполнители открывать отдельные счета?</summary><p>Как правило, да: каждый участник кооперации открывает отдельный счёт под тот же контракт, а головной исполнитель уведомляет соисполнителей и переносит существенные условия ГОЗ в договоры с ними.</p></details>
      <details><summary>Какой вид цены указывать в контракте ГОЗ?</summary><p>Ориентировочную (уточняемую), фиксированную или возмещающую издержки — в зависимости от контракта. Вид цены и условия её перевода в фиксированную должны быть зафиксированы в контракте явно.</p></details>
      <details><summary>Кто поможет проверить контракт по ГОЗ?</summary><p>Проверку существенных условий, открытие нужного счёта и настройку расчётов можно передать на сопровождение. Эксперт сверит контракт по чек-листу и поможет не допустить нарушений. Оставьте заявку — разберём ваш контракт.</p></details>
