    <h2 id="chto-takoe">Что такое существенные условия контракта по ГОЗ</h2>
    <div class="answer reveal">
      <p class="lead-p">Существенные условия контракта по гособоронзаказу — это условия, без согласования которых государственный контракт по ГОЗ считается незаключённым: предмет, цена и её вид, идентификатор государственного контракта (ИГК), отдельный счёт и режим его использования, условие о сопровождении (банковском или казначейском), а также обязанности сторон. Они вытекают из Федерального закона № 44-ФЗ (общие условия контракта, статья 34) и Федерального закона от 29.12.2012 № 275-ФЗ «О государственном оборонном заказе», который добавляет специфические требования ГОЗ.<a class="fn" href="#ref-1" aria-label="Источник 1">[1]</a></p>
      <p>Для исполнителя это не теория: именно существенные условия определяют, как пойдут деньги по контракту, какой счёт открывать, как помечать платежи и что требовать от соисполнителей. Ошибка или пробел в этих условиях оборачивается отказами при расчётах и спорами с заказчиком. Поэтому контракт по ГОЗ читают не «по диагонали», а сверяют по чек-листу существенных условий — его мы приводим ниже.</p>
