    <h2 id="cena">Цена контракта и её вид</h2>
    <div class="answer reveal">
      <p>Цена — существенное условие любого контракта, но в ГОЗ важен ещё и вид цены: ориентировочная (уточняемая), фиксированная или возмещающая издержки. От вида цены зависит порядок расчётов, обоснование затрат и условие о переводе ориентировочной цены в фиксированную. Эти нюансы детально разобраны в материалах <a href="/baza-znaniy/vidy-cen-goz/">«Виды цен на продукцию ГОЗ»</a> и <a href="/baza-znaniy/perevod-orientirovochnoy-ceny-v-fiksirovannuyu-goz/">«Перевод ориентировочной цены в фиксированную»</a>. В контракте вид цены и условия её изменения должны быть зафиксированы явно. Обоснование цены готовят в составе <a href="/baza-znaniy/rkm-po-gosoboronzakazu/">расчётно-калькуляционных материалов (РКМ)</a>.</p>
    </div>

    <h2 id="soisp">Соисполнители и кооперация</h2>
    <div class="answer reveal">
      <p>Гособоронзаказ почти всегда исполняется через кооперацию, поэтому контракт содержит условия о работе с соисполнителями. Головной исполнитель обязан уведомлять соисполнителей о том, что расчёты по ГОЗ ведутся через отдельные счета, и включать в договоры с ними идентификатор контракта. Каждый участник кооперации, как правило, открывает свой отдельный счёт под тот же контракт, чтобы цепочка платежей оставалась прослеживаемой от заказчика до последнего поставщика.</p>
      <p>Для исполнителя это означает дополнительную дисциплину: договоры с соисполнителями нельзя заключать «как обычно» — в них переносят существенные условия ГОЗ. Сопровождение цепочки кооперации тесно связано с раздельным учётом затрат по контракту, который разобран в статье <a href="/baza-znaniy/razdelnyy-uchet-goz-275-fz/">«Раздельный учёт по ГОЗ»</a>.</p>
