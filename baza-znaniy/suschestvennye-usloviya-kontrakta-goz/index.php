    <h2 id="pravovaya">Правовая база: 44-ФЗ и 275-ФЗ вместе</h2>
    <div class="answer reveal">
      <p>Контракт по ГОЗ живёт на стыке двух законов. Общие требования к контракту — срок, ответственность, порядок приёмки, неустойка — задаёт 44-ФЗ (если закупка идёт по нему). Специальные требования гособоронзаказа — отдельные счета, режим использования средств, идентификатор, сопровождение, правила кооперации — устанавливает 275-ФЗ. Поэтому существенные условия контракта по ГОЗ всегда шире, чем у обычного госконтракта.</p>
      <p>Дополнительно Правительство РФ утвердило типовые условия контрактов, заключаемых в целях выполнения государственного оборонного заказа, — их включают в контракты, чтобы унифицировать формулировки об отдельных счетах, сопровождении и кооперации.<a class="fn" href="#ref-2" aria-label="Источник 2">[2]</a> На практике это означает, что часть существенных условий приходит в контракт уже в стандартизированном виде.</p>
