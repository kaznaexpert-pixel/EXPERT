    <h2 id="otdelnyy">Отдельный счёт и режим использования средств</h2>
    <div class="answer reveal">
      <p>Ключевая особенность ГОЗ — расчёты идут не с обычного расчётного счёта, а через отдельный счёт, на который распространяется специальный режим использования средств. Контракт прямо предусматривает условие об осуществлении расчётов только через такой счёт и о соблюдении режима его использования: средства можно тратить строго на цели контракта, а ряд операций ограничен. Это и есть основа прослеживаемости денег в гособоронзаказе.</p>
      <p>Режим использования отдельного счёта означает, что банк или казначейство контролирует назначение каждого платежа. По сути это та же логика обособления и контроля целевых средств, что и при казначейском сопровождении: деньги «окрашены» и не смешиваются с прочими средствами исполнителя. Нарушение режима ведёт к отказам в проведении операций.</p>
    </div>

    <h2 id="igk">Идентификатор государственного контракта в условиях ГОЗ</h2>
    <div class="answer reveal">
      <p>Существенное условие контракта по ГОЗ — наличие идентификатора государственного контракта (ИГК) и обязанность указывать его во всех связанных документах: в номере контракта, в платёжных документах, во внутренних распоряжениях исполнителя и в договорах с соисполнителями. ИГК «склеивает» всю цепочку расчётов по контракту, поэтому его корректность критична. В гособоронзаказе применяется отдельный 25-значный идентификатор; детально структура и отличия разобраны в статье <a href="/baza-znaniy/identifikator-gosudarstvennogo-kontrakta-igk/">«Идентификатор государственного контракта (ИГК)»</a>.</p>
    </div>

    <h2 id="soprovozhdenie">Банковское и казначейское сопровождение ГОЗ</h2>
    <div class="answer reveal">
      <p>Контракт по ГОЗ обязательно содержит условие о сопровождении расчётов, но его форма различается. По умолчанию для гособоронзаказа применяется банковское сопровождение: исполнитель открывает отдельные счета в уполномоченном банке и заключает договор о банковском сопровождении. Для отдельных контрактов ГОЗ предусмотрено казначейское сопровождение — тогда расчёты идут через лицевой счёт в территориальном органе Федерального казначейства с санкционированием операций.</p>
      <p>Различать формы важно, потому что от этого зависит, где открывать счёт и кто контролирует платежи. Если ваш контракт переведён на казначейское сопровождение, ориентируйтесь на разбор <a href="/baza-znaniy/kaznacheyskoe-soprovozhdenie-goz-275-fz/">«Казначейское сопровождение ГОЗ по 275-ФЗ»</a> — там подробно про лицевой счёт, санкционирование и раздельный учёт.</p>
