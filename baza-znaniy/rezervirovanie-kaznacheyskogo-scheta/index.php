    <h2 id="korotkiy-otvet">Короткий ответ: что такое резервирование казначейского счёта</h2>
    <div class="answer reveal"><p>Резервирование казначейского счёта — это получение номера лицевого счёта в территориальном органе казначейства заранее, до заключения контракта. По заявлению организации ТОФК закрепляет за ней реквизиты счёта, и их можно сразу указать в заявке на тендер или в проекте контракта. Заявление подаётся по форме по КФД 0531368 через ГИИС «Электронный бюджет» и обрабатывается, как правило, за один рабочий день.</p></div>

    <h2 id="zachem">Зачем резервировать счёт заранее</h2>
    <p>Резервирование решает проблему сроков: реквизиты казначейского счёта иногда нужны ещё до того, как контракт подписан, — например, чтобы указать их в заявке или в проекте контракта. Без зарезервированного номера пришлось бы ждать открытия счёта уже после подписания, теряя время на старте.</p>
    <p>Получив номер заранее, участник казначейского сопровождения выходит на подписание контракта подготовленным: реквизиты известны, а открытие счёта проходит быстрее, потому что часть данных уже в системе.</p>

    <h2 id="srok-forma">Срок резервирования и форма заявления</h2>
    <p>Зарезервированный номер действует ограниченный срок. Если в течение <b>6 месяцев</b> с даты резервирования участник не представит документы на открытие лицевого счёта, резерв аннулируется, и номер придётся получать заново.</p>
    <p>Заявление оформляется по единой форме — заявление на резервирование (открытие, закрытие) лицевого счёта по форме по КФД <b>0531368</b>. Подача полностью электронная, через ГИИС «Электронный бюджет», личный визит в казначейство не требуется.</p>

    <h2 id="kogda">Когда резервирование нужно</h2>
    <ul>
      <li>Реквизиты счёта требуется указать в заявке на участие в закупке или в проекте контракта.</li>
      <li>Нужно сократить срок между подписанием контракта и первым платежом.</li>
      <li>Контракт с высокой вероятностью попадёт под казначейское сопровождение, и счёт понадобится в любом случае.</li>
    </ul>
    <p>Если контракт под сопровождение не подпадает, резервировать счёт не нужно. Проверить основания — в разборе <a href="/baza-znaniy/kto-popadaet-pod-kaznacheyskoe-soprovozhdenie/">кто попадает под казначейское сопровождение</a>.</p>

    <h2 id="rezerv-vs-otkrytie">Резервирование и открытие счёта — не одно и то же</h2>
    <p>Резервирование не заменяет открытие, а предшествует ему. При резервировании участник получает только номер счёта — проводить операции по нему нельзя. Счёт становится рабочим лишь после заключения контракта и представления полного пакета документов на открытие.</p>
    <p>Как проходит само открытие и какие документы нужны (карточка образцов подписей и учредительные документы больше не требуются) — в инструкции <a href="/baza-znaniy/licevoy-schet-71-kak-otkryt/">как открыть лицевой счёт 71</a>.</p>

