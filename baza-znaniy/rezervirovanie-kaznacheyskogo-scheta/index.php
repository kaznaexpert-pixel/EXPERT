      <li>Сформировать заявление на резервирование по форме по КФД 0531368.</li>
      <li>Направить заявление в территориальный орган казначейства через систему.</li>
      <li>Получить зарезервированный номер счёта (обычно в течение рабочего дня) и использовать его в заявке или проекте контракта.</li>
