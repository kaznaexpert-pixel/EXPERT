    <h2 id="operacii">Сведения об операциях, коды и санкционирование</h2>
    <div class="answer reveal">
      <p>Сердце режима — санкционирование. Это проверка, которую ТОФК проводит по каждому платежу перед списанием: операция сверяется с условиями контракта, целевым назначением и комплектом подтверждающих документов. Чтобы платежи проходили, исполнитель заранее утверждает сведения об операциях с целевыми средствами — документ, где раскрыта структура планируемых расходов по кодам направления расходования.</p>
      <p>Каждый платёж сопровождается идентификатором государственного контракта (ИГК), кодом направления расходования и пакетом документов под конкретный расход. Если кода нет в сведениях, ИГК не проставлен или документы не подтверждают расход — последует отказ. Самые частые причины возвратов и чек-лист, который их снимает, мы собрали в отдельном разборе <a href="/baza-znaniy/prichiny-otkaza-kaznacheystva-v-sankcionirovanii/">«Причины отказа казначейства в санкционировании»</a>. Как заполнить сами сведения об операциях — в материале <a href="/baza-znaniy/svedeniya-ob-operaciyah-s-celevymi-sredstvami/">«Сведения об операциях с целевыми средствами»</a>.</p>
