    <div class="answer reveal">
      <p>Казначейское сопровождение — это не только про госконтракты. Под режим попадают и другие формы бюджетного финансирования: субсидии юридическим лицам, бюджетные инвестиции, средства по концессионным соглашениям и соглашениям о государственно-частном партнёрстве<a class="fn" href="#ref-2" aria-label="Источник 2">[2]</a>. Логика та же — государство контролирует целевое расходование, но получателем выступает не подрядчик по контракту, а получатель субсидии или инвестиции.</p>
      <p>Для бизнеса это означает, что компания может столкнуться с КС, даже не участвуя в госзакупках напрямую: например, получив целевую субсидию на проект. Принцип работы при этом сохраняется — отдельный счёт или режим расчётов, сведения об операциях, подтверждающие документы под каждый расход. Конкретные категории субсидий под сопровождением и пороги на текущий год определяются законом о бюджете и решениями о предоставлении средств, поэтому проверять условия нужно по своему договору (соглашению).</p>
    </div>

    <h2 id="oshibki">Частые ошибки исполнителей при казначейском сопровождении</h2>
    <div class="answer reveal">
      <p>Большинство проблем при КС возникает не из-за сложности норм, а из-за того, что режим воспринимают как обычный коммерческий договор. Ниже — типовые ошибки, которые на практике приводят к возвратам платежей, срыву сроков оплаты поставщикам и спорам с заказчиком, и как их не допустить.</p>
    </div>
    <table>
      <caption>Типовые ошибки при работе с казначейским сопровождением и решения</caption>
      <tr><th>Ошибка</th><th>К чему приводит</th><th>Как правильно</th></tr>
      <tr><td>Не проверили условие о КС в контракте</td><td>Деньги приходят на счёт под контролем, а схема расчётов не готова</td><td>До подписания проверить, попадает ли контракт под КС и какой режим расчётов применяется</td></tr>
      <tr><td>Считают аванс «своими» деньгами</td><td>Первый же платёж возвращают — средства целевые</td><td>Планировать расходы аванса в сведениях об операциях по кодам</td></tr>
      <tr><td>Сведения об операциях не утверждены вовремя</td><td>Платежи по коду не проходят санкционирование</td><td>Утвердить сведения до начала расчётов и поддерживать их актуальными</td></tr>
