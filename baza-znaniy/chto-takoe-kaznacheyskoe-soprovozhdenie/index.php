        <li>Казначейское сопровождение — предварительный контроль целевого расходования бюджетных средств через спецсчёт и санкционирование каждого платежа.</li>
        <li>Основа — глава 24.4 Бюджетного кодекса и Правила Правительства № 2024; конкретные пороги задаёт закон о бюджете на год.</li>
        <li>В 2026 году пороги и перечень средств установлены ст. 5 закона № 426-ФЗ: федеральные госконтракты — от 100 млн ₽, контракты учреждений — от 10 млн ₽, авансы — по договорам свыше 3 млн ₽.</li>
