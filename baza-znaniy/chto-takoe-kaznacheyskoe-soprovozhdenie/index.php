    <h2 id="faq">Частые вопросы</h2>
    <div class="faq">
      <details open><summary>Что такое казначейское сопровождение простыми словами?</summary><p>Это режим, при котором бюджетные деньги по контракту или субсидии проходят через специальный счёт под контролем Федерального казначейства, а каждый платёж согласуется. Цель — чтобы средства расходовались строго на исполнение контракта.</p></details>
      <details><summary>Какие контракты попадают под КС в 2026 году?</summary><p>В первую очередь крупные: госконтракты для федеральных нужд от 100 млн ₽, контракты бюджетных и автономных учреждений от 10 млн ₽, а также субсидии, бюджетные инвестиции и средства по концессиям в случаях, установленных законом № 426-ФЗ.</p></details>
      <details><summary>От какой суммы действует казначейское сопровождение?</summary><p>Единого порога нет — он зависит от категории средств. Для федеральных госконтрактов ориентир — 100 млн ₽, для контрактов учреждений — 10 млн ₽, для авансов исполнителей и соисполнителей — договоры свыше 3 млн ₽. Точные значения смотрите в ст. 5 закона о бюджете на 2026 год.</p></details>
      <details><summary>Чем казначейское сопровождение отличается от банковского?</summary><p>Контролёр разный: при казначейском контроль ведёт Федеральное казначейство и счёт открывается в ТОФК, при банковском — уполномоченный банк. Казначейское — это предварительный контроль каждого платежа, банковское чаще мониторинг.</p></details>
      <details><summary>Что такое расширенное казначейское сопровождение?</summary><p>Это режим по ст. 242.24 БК РФ, где казначейство проверяет не только целевое назначение платежа, но и фактические затраты и обоснованность цены. При нём обязателен раздельный учёт по контракту.</p></details>
      <details><summary>Нужно ли открывать счёт в казначействе?</summary><p>Часто да — лицевой счёт 71 в ТОФК. Но в 2026 году для части исполнителей продлён упрощённый порядок: расчёты идут на расчётный счёт в банке без открытия счёта в казначействе. Какой режим применяется — зависит от конкретного контракта.</p></details>
      <details><summary>Можно ли вывести деньги со счёта под КС на обычный счёт?</summary><p>Свободно — нет. Средства целевые; перечисление возможно только в установленных случаях и после санкционирования операции. Расходы вне режима счёта казначейство не пропустит.</p></details>
      <details><summary>Что проверяет казначейство при платеже?</summary><p>Соответствие операции контракту, целевое назначение, наличие ИГК и корректного кода направления расходования, комплект подтверждающих документов и соответствие суммы условиям контракта.</p></details>
      <details><summary>Что будет, если нарушить порядок КС?</summary><p>Конкретный платёж вернут без исполнения, а при нецелевом использовании средств возможна административная ответственность. Системные нарушения создают риск претензий по контракту, поэтому дисциплина документов критична.</p></details>
      <details><summary>Распространяется ли КС на соисполнителей?</summary><p>Да. Если головной контракт под казначейским сопровождением, договоры с соисполнителями в рамках его исполнения подпадают под тот же режим. Это нужно учитывать при выборе поставщиков.</p></details>
      <details><summary>Можно ли разместить целевые средства на депозите?</summary><p>Режим счёта это ограничивает: даже если средства размещены в финансовые инструменты, и они сами, и полученный доход подлежат возврату на лицевой счёт под казначейским сопровождением. Свободно «прокрутить» целевые деньги нельзя.</p></details>
      <details><summary>Когда можно вывести прибыль по контракту?</summary><p>После исполнения контракта прибыль перечисляется в установленном порядке. Если её размер превышает 20% суммы контракта, подлежащей уплате в текущем году, казначейство вправе приостановить операцию на срок до 5 рабочих дней для проверки.</p></details>
      <details><summary>Сколько длится проверка платежа?</summary><p>Отдельного «единого срока» на каждый платёж нет, но при выявлении нарушения документ возвращается в срок до 1 рабочего дня, а сведения об операциях заказчик утверждает не позднее 10-го рабочего дня. Планировать платежи стоит с запасом в несколько рабочих дней.</p></details>
      <details><summary>Кто утверждает сведения об операциях?</summary><p>Сведения формирует исполнитель, а утверждает заказчик (получатель бюджетных средств) — не позднее 10-го рабочего дня после их получения. Без утверждённых сведений платежи по соответствующим кодам не пройдут.</p></details>
      <details><summary>Кто помогает настроить казначейское сопровождение?</summary><p>Сопровождение можно передать на аутсорсинг: эксперт открывает счёт, готовит сведения об операциях, ведёт платежи и взаимодействует с ТОФК. Оставьте заявку — разберём ваш контракт и подскажем порядок действий.</p></details>
