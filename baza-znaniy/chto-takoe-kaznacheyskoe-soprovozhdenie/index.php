    <div class="answer reveal">
      <p>Объединяет эти ошибки одно: режим пытаются «достроить» уже после получения денег. На практике дешевле и быстрее настроить всё заранее — счёт или порядок банковских расчётов, сведения об операциях, коды и шаблоны документов. Тогда казначейское сопровождение перестаёт быть тормозом и становится просто частью обычного документооборота по контракту.</p>
    </div>

    <h2 id="keys">Пример из практики</h2>
    <div class="answer reveal">
      <p>Типичная ситуация: компания выигрывает контракт на поставку оборудования для государственного заказчика на сумму выше порога. В контракте есть условие о казначейском сопровождении, но исполнитель планирует расчёты как по обычному коммерческому договору — получить аванс и свободно платить поставщикам. На практике это приводит к первому же возврату платежа: средства «окрашены», и без утверждённых сведений об операциях, корректного кода направления и подтверждающих документов казначейство расход не пропускает. После того как заранее настроены счёт (или режим банковских расчётов), сведения об операциях и комплект документов под каждый код, платежи начинают проходить штатно. Вывод, который подтверждается на практике: режим КС выгоднее настроить до получения первого аванса, а не разбираться с ним после первого отказа.</p>
    </div>

